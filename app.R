# ---- Server ------------------------------------------------------------------
server <- function(input, output, session) {

  catalog <- reactive(readRDS(file.path(DATA_DIR, paste0("catalog_", input$year, ".rds"))))
  geo     <- reactive(readRDS(file.path(DATA_DIR, sprintf("%s_%s_geo.rds", input$year, input$level))))

  var_choices <- function(cat) {
    grp <- paste(cat$source, "-", ifelse(is.na(cat$theme) | cat$theme == "", "Other", cat$theme))
    split(setNames(cat$id, cat$label), grp)
  }

  observeEvent(catalog(), {
    cat <- catalog(); ch <- var_choices(cat)
    keep <- function(cur, fallback) if (isTruthy(cur) && cur %in% cat$id) cur else fallback
    updateSelectizeInput(session, "xvar", choices = ch, selected = keep(input$xvar, cat$id[1]))
    updateSelectizeInput(session, "yvar", choices = ch, selected = keep(input$yvar, cat$id[min(2, nrow(cat))]))
  })

  observeEvent(geo(), {
    cities <- sort(unique(geo()$gemeente))
    updateSelectizeInput(session, "city", choices = cities,
                         selected = if (isTruthy(input$city) && input$city %in% cities) input$city else cities[1],
                         server = TRUE)
  })

  lab <- function(id) {
    r <- catalog()[catalog()$id == id[1], ][1, ]
    u <- r$unit[1]
    paste0(r$label[1], if (isTRUE(!is.na(u) && nzchar(u))) paste0(" (", u, ")") else "")
  }

  dat <- reactive({
    req(input$city, input$xvar, input$yvar)
    validate(need(input$xvar != input$yvar, "Pick two different variables."))
    path <- file.path(DATA_DIR, sprintf("%s_%s.parquet", input$year, input$level))
    v <- read_parquet(path, col_select = c("code", input$xvar, input$yvar))
    geo() |> filter(gemeente == input$city) |> left_join(v, by = "code")
  })
  complete <- reactive({
    d <- dat()
    d[!is.na(d[[input$xvar]]) & !is.na(d[[input$yvar]]), ]
  })
  output$nobs <- renderText({
    req(dat())
    paste0("n = ", nrow(complete()), " of ", nrow(dat()), " areas have data for both variables.")
  })

  caption <- reactive(paste0("n = ", nrow(complete()), " | ", input$city, ", ", input$year))

  # ---- Scatter plot ----
  build_scatter <- function(interactive = TRUE) {
    d <- st_drop_geometry(complete()); x <- input$xvar; y <- input$yvar
    validate(need(nrow(d) >= 3, "Too few areas with data for both variables."))
    pt <- if (interactive)
      geom_point_interactive(aes(tooltip = name, data_id = code), colour = input$p_pcol,
                             size = input$p_psize, alpha = input$p_alpha)
    else geom_point(colour = input$p_pcol, size = input$p_psize, alpha = input$p_alpha)
    th <- switch(input$p_theme, minimal = theme_minimal, bw = theme_bw,
                 classic = theme_classic, light = theme_light)
    p <- ggplot(d, aes(x = .data[[x]], y = .data[[y]])) + pt
    if (input$p_line)
      p <- p + geom_smooth(method = "lm", formula = y ~ x, se = FALSE, colour = input$p_lcol, linewidth = 1)
    p <- p +
      labs(title = blank(input$p_title), subtitle = blank(input$p_sub),
           x = blank(input$p_x, lab(x)), y = blank(input$p_y, lab(y)), caption = caption()) +
      th(base_size = input$p_size, base_family = input$p_family) +
      theme(plot.title = element_text(size = input$p_tsize, face = "bold"),
            plot.subtitle = element_text(size = input$p_tsize * 0.7))
    if (!input$p_grid) p <- p + theme(panel.grid = element_blank())
    p
  }
  output$scatter <- renderGirafe(girafe(ggobj = build_scatter(TRUE), width_svg = 8, height_svg = 5.5))

  # ---- Map ----
  build_map <- function() {
    d <- dat(); x <- input$xvar; y <- input$yvar
    cc <- as.data.frame(st_drop_geometry(d)[!is.na(d[[x]]) & !is.na(d[[y]]), ])
    validate(need(nrow(cc) >= 10, "Too few areas with data to draw a map."))
    cap <- paste0("n = ", nrow(cc), " of ", nrow(d), " areas with data | ", input$city, ", ", input$year)
    base <- ggplot(d)
    ttl  <- labs(title = blank(input$m_title), subtitle = blank(input$m_sub), caption = cap)
    ttheme <- theme(plot.title = element_text(size = input$m_tsize, face = "bold"),
                    plot.subtitle = element_text(size = input$m_tsize * 0.7))
    bcol <- input$m_bcol; bw <- input$m_bw
    border <- if (bw > 0) list(colour = bcol, linewidth = bw) else list(colour = NA)

    if (input$m_type == "bi") {
      dim <- as.numeric(input$m_dim)
      ok  <- !is.na(d[[x]]) & !is.na(d[[y]])
      q <- function(v) {                       # quantile classes 1..dim
        brk <- unique(quantile(v[ok], seq(0, 1, length.out = dim + 1)))
        findInterval(v, brk, rightmost.closed = TRUE, all.inside = TRUE)
      }
      d$bi_class <- ifelse(ok, paste0(q(d[[x]]), "-", q(d[[y]])), NA)
      m <- ggplot(d) +
        do.call(geom_sf, c(list(mapping = aes(fill = bi_class), show.legend = FALSE), border)) +
        bi_scale_fill(pal = input$m_pal, dim = dim, na.value = "grey85") +
        ttl + bi_theme(base_size = input$m_size) + ttheme
      wrap_txt <- function(s) paste(strwrap(s, width = 16), collapse = "\n")
      leg <- bi_legend(pal = input$m_pal, dim = dim, size = input$m_lsize,
                       xlab = wrap_txt(paste0("Higher ", lab(x))),
                       ylab = wrap_txt(paste0("Higher ", lab(y))))
      plot_grid(m, leg, nrow = 1, rel_widths = c(3, 1.8))
    } else {
      v <- if (input$m_var == "x") x else y
      brk <- unique(quantile(cc[[v]], seq(0, 1, length.out = input$m_k + 1), na.rm = TRUE))
      validate(need(length(brk) >= 3, "Not enough variation to make classes."))
      d$cls <- cut(d[[v]], brk, include.lowest = TRUE, dig.lab = 4)
      ggplot(d) +
        do.call(geom_sf, c(list(mapping = aes(fill = cls)), border)) +
        scale_fill_brewer(palette = input$m_spal, na.value = "grey85", name = lab(v), na.translate = FALSE) +
        ttl + theme_void(base_size = input$m_size) + ttheme
    }
  }
  output$map <- renderPlot(build_map(), res = 110)

  # ---- Downloads: figures ----
  fig_dl <- function(name, fn, p) downloadHandler(
    filename = function() paste0(name, "_", safe(input$city), ".", input[[paste0(p, "_fmt")]]),
    content = function(file) ggsave(file, fn(), width = input[[paste0(p, "_w")]],
                                    height = input[[paste0(p, "_h")]], units = "cm",
                                    dpi = input[[paste0(p, "_dpi")]])
  )
  output$dl_plot <- fig_dl("scatter", function() build_scatter(FALSE), "p")
  output$dl_map  <- fig_dl("map", build_map, "m")

  # ---- Downloads: data + metadata + script ----
  output$dl_pack <- downloadHandler(
    filename = function() paste0("analysis_", input$year, "_", safe(input$city), ".zip"),
    content = function(file) {
      x <- input$xvar; y <- input$yvar; cat <- catalog()
      tmp <- tempfile(); dir.create(tmp)
      cs <- complete(); d <- st_drop_geometry(cs)

      out <- data.frame(area_code = d$code, area_name = d$name, municipality = d$gemeente)
      out[[x]] <- d[[x]]; out[[y]] <- d[[y]]
      write.csv(out, file.path(tmp, "data.csv"), row.names = FALSE, fileEncoding = "UTF-8")
      st_write(cs[c("code", "name", "gemeente", x, y)], file.path(tmp, "areas.gpkg"), quiet = TRUE)

      info <- cat[cat$id %in% c(x, y), ]
      srcs <- paste(unique(paste0(info$source, " table ", info$table)), collapse = "; ")
      writeLines(c(
        "Buurt Explorer - download metadata",
        paste("Downloaded:", Sys.Date()),
        paste("Data build date:", format(max(cat$built))),
        paste("Year (data and boundaries):", input$year, "(CBS/PDOK wijken en buurten)"),
        paste("Municipality:", input$city, "| level:", input$level, "| n =", nrow(out)),
        paste("Sources:", srcs), "",
        "Variables:",
        paste0("  ", info$id, ": ", info$label, " [", ifelse(is.na(info$unit), "", info$unit),
               "] (", info$source, " ", info$table, ")"), "",
        "Caveat: neighbouring areas are not independent (spatial autocorrelation) and",
        "area-level correlations do not apply to individuals (ecological fallacy)."
      ), file.path(tmp, "README_metadata.txt"))

      vals <- list(date = Sys.Date(), sources = srcs, year = input$year, city = input$city,
                   level = input$level, x = x, y = y, xlabel = lab(x), ylabel = lab(y))
      if (input$script_lang == "R")
        writeLines(fill(TPL_R, vals), file.path(tmp, "analysis.R"))
      else
        writeLines(fill(TPL_SPSS, vals), file.path(tmp, "analysis.sps"))

      zip::zipr(file, list.files(tmp), root = tmp)
    }
  )
}

shinyApp(ui, server)
